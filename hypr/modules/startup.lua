    hl.exec_cmd("swaync")
    hl.exec_cmd("udiskie &")
    hl.exec_cmd("fxitx5 &")
    hl.exec_cmd("hyprpaper")
    hl.exec_cmd("quickshell")
    hl.exec_cmd("hyprsunset")
